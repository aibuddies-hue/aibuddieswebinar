def remap(text):
    for old, new in MAP:
        text = re.sub(re.escape(old), new, text, flags=re.I)
    return text

def has_blue(text):
    low = text.lower()
    return any(old.lower() in low for old, _ in MAP)

def main():
    css = io.open(SRC, encoding="utf-8").read()

    header = ("/* GENERATED by tools/build-theme.py from style.css — do not edit by hand.\n"
              " *\n"
              " * A complete copy of the stylesheet with the blue palette swapped for\n"
              " * Claude's clay and cream. The free pages load THIS INSTEAD OF style.css.\n"
              " *\n"
              " * It is a whole copy rather than an override layer on purpose. Scoping a\n"
              " * subset of rules moves them to the end of the cascade, which twice broke\n"
              " * the page: it made an early rule outrank the later one meant to beat it,\n"
              " * blacking out the hero headline, and then flipped the logistics strip\n"
              " * back to a white card on a dark hero. Copying everything in order keeps\n"
              " * source order and specificity exactly as they were.\n"
              " *\n"
              " * Re-run from the repo root after changing style.css:\n"
              " *     python3 tools/build-theme.py\n"
              " */\n")

    io.open(OUT, "w", encoding="utf-8").write(header + remap(css))

    missed = [old for old, _ in MAP if old.lower() in remap(css).lower()]
    print("themed stylesheet written;", len(css.splitlines()), "lines")
    print("blue literals left:", missed if missed else "none")

main()
